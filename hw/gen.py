#!/usr/bin/env python3
"""Turns `mca-check --describe` output into C: each thread of each test becomes one inline-assembly
block holding exactly the test's instructions, as litmus7 does.

    python3 gen.py tests.jsonl tests_gen.c

For each thread:
  - its initial registers are loaded first: the address of this instance's cell for a location,
    or an integer;
  - its code follows, verbatim, with each label made unique to the block (LC00 -> LC00_%=);
  - the registers the condition reads are stored to `out`;
  - every register the code touches is declared clobbered, so the compiler keeps the inputs
    elsewhere.
"""
import json
import re
import sys

RESERVED = {18}  # x18 is the platform register on Android (shadow call stack)


def c_ident(name, k):
    return "t%d_" % k + re.sub(r"[^A-Za-z0-9]", "_", name)


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def thread_body(fn, th, obs):
    code = th["code"]
    labels = [c[:-1] for c in code if c.endswith(":")]
    regs = set()
    for line in code:
        regs |= {int(r) for r in re.findall(r"\b[WXwx](\d+)\b", line)}
    regs |= {int(r) for r in th["init"]}
    if regs & RESERVED:
        raise ValueError("uses x18, which Android reserves")

    lines = []
    inputs = []
    for reg, val in sorted(th["init"].items(), key=lambda kv: int(kv[0])):
        name = "in%s" % reg
        lines.append("mov x%s, %%[%s]" % (reg, name))
        if "loc" in val:
            inputs.append('[%s] "r"(&L[%d][i].v)' % (name, val["loc"]))
        else:
            inputs.append('[%s] "r"((uint64_t)%dLL)' % (name, val["int"]))
    # herd starts every other register at 0
    for reg in sorted(regs - {int(r) for r in th["init"]}):
        lines.append("mov x%d, #0" % reg)
    for line in code:
        for lab in labels:
            # .L: an assembler-local label, unique to this asm block (%=), that leaves no symbol
            line = re.sub(r"\b%s\b" % re.escape(lab), ".L" + lab + "_%=", line)
        lines.append(line)
    for slot, o in enumerate(obs):
        lines.append("str x%d, [%%[out], #%d]" % (o["reg"], 8 * slot))
    inputs.append('[out] "r"(out)')
    clobbers = ", ".join(c_str("x%d" % r) for r in sorted(regs)) + ', "memory", "cc"'
    # Each line becomes "<instruction>\n\t" in the C source: a real newline for the assembler.
    template = "\n".join('        "%s\\n\\t"' % l.replace("\\", "\\\\").replace('"', '\\"') for l in lines)
    return f"""static void {fn}(cell_t* const* L, size_t i, uint64_t* out) {{
    (void)L; (void)i; (void)out;
    __asm__ __volatile__(
        ".arch_extension lse\\n\\t"
        ".arch_extension rcpc\\n\\t"
{template}
        :
        : {", ".join(inputs)}
        : {clobbers});
}}
"""


def main():
    src, dst = sys.argv[1], sys.argv[2]
    tests = [json.loads(l) for l in open(src) if l.strip()]
    out = ['// Generated by gen.py from mca-check --describe. Do not edit.',
           '#include "harness.h"', '']
    entries = []
    skipped = []
    for k, t in enumerate(tests):
        if not t.get("supported"):
            skipped.append((t["name"], t.get("error", "")))
            continue
        if len(t["threads"]) > 4 or len(t["locations"]) > 8 or len(t["observed"]) > 8:
            skipped.append((t["name"], "too big for the harness"))
            continue
        if any("=" in s and re.search(r"=[A-Za-z_]", s) for s in t["allowed"]):
            skipped.append((t["name"], "observes an address"))
            continue
        base = c_ident(t["name"], k)
        try:
            fns = []
            slots = []
            obs_slot = {}
            for ti, th in enumerate(t["threads"]):
                mine = [o for o in t["observed"] if o["thread"] == ti]
                for s, o in enumerate(mine):
                    obs_slot[o["name"]] = s
                fn = "%s_p%d" % (base, ti)
                out.append(thread_body(fn, th, mine))
                fns.append(fn)
                slots.append(len(mine))
        except ValueError as e:
            skipped.append((t["name"], str(e)))
            continue
        out.append("static int %s_cond(const uint64_t* v) { (void)v; return %s; }" % (base, t["condition_c"]))
        out.append("static const char* const %s_allowed[] = {%s, NULL};" % (base, ", ".join(c_str(s) for s in t["allowed"])))
        out.append("")
        obs = t["observed"]
        entries.append("""    {{ .name = {name}, .nthreads = {nt}, .nlocs = {nl}, .nobs = {no},
      .loc_name = {{ {ln} }}, .loc_init = {{ {li} }},
      .obs_name = {{ {on} }}, .obs_thread = {{ {ot} }}, .obs_slot = {{ {os} }}, .obs_loc = {{ {ol} }},
      .nslots = {{ {ns} }}, .body = {{ {fns} }}, .cond = {base}_cond, .quantifier = {q}, .model = {m},
      .allowed = {base}_allowed, .needs_lse = {lse}, .needs_rcpc = {rcpc} }},""".format(
            name=c_str(t["name"]), nt=len(t["threads"]), nl=len(t["locations"]), no=len(obs),
            ln=", ".join(c_str(l["name"]) for l in t["locations"]),
            li=", ".join("%dULL" % l["init"] for l in t["locations"]),
            on=", ".join(c_str(o["name"]) for o in obs),
            ot=", ".join(str(o["thread"]) for o in obs),
            os=", ".join(str(obs_slot.get(o["name"], -1)) for o in obs),
            ol=", ".join(str(o["loc"]) for o in obs),
            ns=", ".join(str(s) for s in slots), fns=", ".join(fns), base=base,
            q=c_str(t["quantifier"]), m=c_str(t["observation"]),
            lse=int("lse" in t["needs"]), rcpc=int("rcpc" in t["needs"])))
    out.append("const test_t TESTS[] = {")
    out += entries
    out.append("};")
    out.append("const int NTESTS = %d;" % len(entries))
    open(dst, "w").write("\n".join(out) + "\n")
    for n, e in skipped:
        print("skipped %s: %s" % (n, e), file=sys.stderr)
    print("generated %d tests" % len(entries), file=sys.stderr)


if __name__ == "__main__":
    main()
